import Foundation

/// Markdown hand-off document: each claim with its status, sources, verified
/// quotes (`IDI #-Q#`) and warnings, followed by the reference list and the
/// project's quote index.
public struct ClaimsReport: Sendable {
    public var library: Library
    public var project: String

    public init(library: Library, project: String) {
        self.library = library
        self.project = project
    }

    static let sectionOrder: [ClaimStatus] = [.supported, .overstated, .unreviewed, .unsupported, .sourceNotFound, .selfCitation]

    public func markdown(generated: Date = Date()) -> String {
        guard let index = library.projects[project] else { return "# \(project)\n\nNo claims recorded.\n" }
        let claims = index.claims
        let cited = Self.unique(claims.filter { $0.status != .dropped }.flatMap(\.references)).compactMap { library[$0] }
        let formatter = CitationFormatter(references: cited)

        var out: [String] = []
        let date = ISO8601DateFormatter.string(from: generated, timeZone: .current, formatOptions: [.withFullDate])
        out.append("# Claims Report — \(project)")
        out.append("")
        let files = Self.unique(claims.compactMap { $0.origin?.file })
        out.append("Generated by RefWare on \(date)" + (files.isEmpty ? "." : " from \(files.map { "`\($0)`" }.joined(separator: ", "))."))
        out.append("")
        out.append("| Status | Claims |")
        out.append("|---|---|")
        for status in Self.sectionOrder + [.dropped] {
            let n = claims.filter { $0.status == status }.count
            if n > 0 { out.append("| \(Self.label(status)) | \(n) |") }
        }
        out.append("")
        out.append("""
        **How to read this.** Only **Supported** claims are ready to draft from: each has at least one quote that RefWare \
        found word-for-word in the source PDF (tag `IDI #-Q#`; page = PDF page, line = text line on that page). Whether \
        a quote *supports* its claim is an editorial judgment recorded by the project lead. Cite in the manuscript with \
        `[IDI #]` or `[IDI #, p. N]`; RefWare expands these to (Author, Year) and builds the reference list.
        """)

        for status in Self.sectionOrder {
            let group = claims.filter { $0.status == status }
            guard !group.isEmpty else { continue }
            out.append("")
            out.append("## \(Self.label(status))")
            for claim in group {
                out.append("")
                out.append(contentsOf: entry(claim, index: index, formatter: formatter))
            }
        }

        out.append("")
        out.append("## References")
        out.append("")
        if cited.isEmpty {
            out.append("_No sources linked yet._")
        } else {
            for ref in CitationFormatter.sorted(cited) {
                out.append("- \(formatter.referenceEntry(ref)) `[IDI \(ref.id)]`")
            }
        }

        let quotes = index.quotes.sorted { ($0.reference, Self.qNumber($0.label)) < ($1.reference, Self.qNumber($1.label)) }
        if !quotes.isEmpty {
            out.append("")
            out.append("## Quote Index")
            out.append("")
            out.append("| Tag | Source | Page | Line | Quote |")
            out.append("|---|---|---|---|---|")
            for q in quotes {
                let who = library[q.reference].map { formatter.inlineBody($0) } ?? "?"
                let text = q.text.replacingOccurrences(of: "|", with: "\\|").replacingOccurrences(of: "\n", with: " ")
                out.append("| \(q.tag) | \(who) | \(q.page.map(String.init) ?? "–") | \(q.line.map(String.init) ?? "–") | \(text) |")
            }
        }
        return out.joined(separator: "\n") + "\n"
    }

    public func entry(_ claim: Claim, index: ProjectCitationIndex, formatter: CitationFormatter) -> [String] {
        var lines = ["### \(claim.id)", "", "> \(claim.text)", ""]
        if let o = claim.origin {
            lines.append("- **Origin:** `\(o.file)` line \(o.line)" + (o.label.map { " — listed as \($0)" } ?? "") + (o.speaker.map { " (\($0))" } ?? ""))
        }

        let titlesResolved = claim.sources.filter { $0.url == nil && $0.title != nil }.allSatisfy { $0.reference != nil }
        var warnings: [String] = claim.flags.filter { !($0 == .unlinkedTitle && titlesResolved) }.map(Self.describe)
        if !claim.sources.isEmpty {
            lines.append("- **Sources:**")
            var shown = Set<IDI>()
            for s in claim.sources {
                if let id = s.reference, !shown.insert(id).inserted { continue }
                if let id = s.reference, let ref = library[id] {
                    var kind = ref.arxiv != nil && ref.doi == nil ? "arXiv preprint" : ref.publicationType.rawValue
                    if ref.provenance?.source == .webPage { kind = "web page — not a scholarly source" }
                    let pdf = ref.fileName == nil ? " · no PDF" : ""
                    let link = ref.fileName == nil ? captureLink(s.url ?? ref.doi.map { "https://doi.org/\($0)" } ?? ref.url, claim: claim.id) : ""
                    lines.append("  - `[IDI \(id)]` \(formatter.inlineBody(ref)) — *\(ref.title)* (\(kind)\(pdf))\(link)")
                    if let url = s.url, index.isSelfSource(url) { warnings.append("Source \(url) is the author's own site (self-citation).") }
                } else if let url = s.url {
                    let mine = index.isSelfSource(url) ? " — the author's own site" : ""
                    lines.append("  - ⚠️ unresolved: \(url)\(mine)\(captureLink(url, claim: claim.id))")
                } else if let title = s.title {
                    let hasLinks = claim.sources.contains { $0.reference != nil }
                    lines.append("  - ⚠️ named but not located: *\(title)*")
                    if hasLinks { warnings.append("The title *\(title)* doesn't match any linked source — check for a mistitled or invented reference.") }
                } else if let marker = s.marker {
                    lines.append("  - ⚠️ footnote [\(marker)] has no URL in the transcript")
                }
            }
        } else {
            lines.append("- **Sources:** none")
        }

        let quotes = claim.quotes.compactMap(index.quote(tag:))
        if !quotes.isEmpty {
            lines.append("- **Evidence:**")
            for q in quotes {
                let who = library[q.reference].map { formatter.inlineBody($0) } ?? "IDI \(q.reference)"
                let loc = [q.page.map { "p. \($0)" }, q.line.map { "line \($0)" }].compactMap { $0 }.joined(separator: ", ")
                let cite = q.page.map { "`[IDI \(q.reference), p. \($0)]`" } ?? "`[IDI \(q.reference)]`"
                lines.append("  - **\(q.tag)** (\(who), \(loc)): \u{201C}\(q.text)\u{201D} → cite as \(cite)")
            }
        }
        for w in Self.unique(warnings) { lines.append("- ⚠️ \(w)") }
        if let who = claim.reviewedBy, claim.status != .unreviewed {
            lines.append("- **Reviewed by:** \(who)" + (claim.reviewedOn.map { " on \($0.formatted(date: .abbreviated, time: .omitted))" } ?? ""))
        }
        if let note = claim.note {
            if note.contains("\n") {
                lines.append("- **Reviewer notes:**")
                lines.append("")
                lines += note.components(separatedBy: "\n").map { $0.isEmpty ? "  >" : "  > \($0)" }
            } else {
                lines.append("- **Note:** \(note)")
            }
        }
        return lines
    }

    /// ` [📥 capture](refware://capture?…)` — opens RefWare Capture, which adds the
    /// source (metadata + PDF or web snapshot) and links it to this claim.
    func captureLink(_ url: String?, claim: String) -> String {
        guard let url, let enc = url.addingPercentEncoding(withAllowedCharacters: .alphanumerics) else { return "" }
        return " [📥 capture](refware://capture?url=\(enc)&project=\(project)&claim=\(claim))"
    }

    static func label(_ s: ClaimStatus) -> String {
        switch s {
        case .unreviewed: "Unreviewed"
        case .supported: "Supported"
        case .overstated: "Overstated"
        case .unsupported: "Unsupported by Source"
        case .sourceNotFound: "Source Not Found"
        case .selfCitation: "Self-Citation"
        case .dropped: "Dropped"
        }
    }

    static func describe(_ f: ClaimFlag) -> String {
        switch f {
        case .unlinkedTitle: "A work is named without a link."
        case .containsQuotation: "Contains a verbatim quotation attributed to a source — verify it against the PDF before use."
        case .uncitedEvidence: "Appeals to research or evidence without citing any."
        case .fragment: "The claim text looks cut off — compare it with the manuscript sentence."
        }
    }

    private static func unique<T: Hashable>(_ xs: [T]) -> [T] {
        var seen = Set<T>()
        return xs.filter { seen.insert($0).inserted }
    }

    private static func qNumber(_ label: String) -> Int { Int(label.dropFirst()) ?? 0 }
}
